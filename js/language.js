// TRANSLATE FUNCTION
// Uses data-key attributes to translate content
// ==============================================

function translate(lang) {

  var t = translations[lang];
  if (!t) return;

  // Lets the stylesheet pick Tamil typography and lets browsers/readers know the language.
  document.documentElement.lang = (lang === "English") ? "en" : "ta";

  var elements = document.querySelectorAll("[data-key]");

  elements.forEach(function (el) {

    var key = el.getAttribute("data-key");
    if (!key) return;

    var text = t[key];
    if (text === undefined) return;

    var tag = el.tagName;

    if (tag === "INPUT" && el.type === "text" && el.hasAttribute("placeholder")) {

      el.placeholder = text;

    } else if (tag === "META") {

      el.setAttribute("content", text);

    } else if (tag === "TITLE") {

      // Don't set title if we're on a category page (handled separately)
      if (!document.querySelector(".category-banner")) {
        el.textContent = text;
      }

    } else if (el.hasAttribute("title")) {

      el.setAttribute("title", text);

    } else if (tag === "OPTION") {

      el.textContent = text;

    } else if (tag === "IMG") {

      el.setAttribute("alt", text);

    } else {

      el.textContent = text;

    }

  });

  // Update page title for non-category pages
  if (t.pageTitle) {
    document.title = t.pageTitle;
  }

  // Update dynamically loaded product cards
  if (window.updateProductLanguage) {
    window.updateProductLanguage(lang);
  }

  // Update category page header (banner, breadcrumb, title)
  if (window.updateCategoryHeader) {
    window.updateCategoryHeader(lang);
  }

  // Update cart page
  if (window.updateCartLanguage) {
    window.updateCartLanguage(lang);
  }

}

// ==============================================
// LANGUAGE SELECT EVENT
// ==============================================

var languageSelect = document.getElementById("language");

if (languageSelect) {

  var savedLang = localStorage.getItem("magizhamLang") || "English";
  languageSelect.value = savedLang;

  languageSelect.addEventListener("change", function () {
    var lang = this.value;
    localStorage.setItem("magizhamLang", lang);
    translate(lang);
  });

  translate(savedLang);

}

